/// 출생 지역 데이터 — 이름으로 검색해 위도·경도를 얻는다.
///
/// 경도는 진태양시(사주 시주·대운) 보정에, 위도는 상승궁(점성학) 근사에 쓴다.
/// 사용자는 더 이상 경도 숫자를 직접 입력하지 않고 지역 이름만 고르면 된다.
/// 좌표는 각 시·군·구청 소재지 기준의 대표값(소수 둘째 자리)이다.

class Region {
  const Region(this.name, this.lat, this.lng, [this.aliases = const []]);

  final String name; // 표시 이름 (예: 서울)
  final double lat; // 위도(북위)
  final double lng; // 경도(동경)
  final List<String> aliases; // 검색 별칭 (예: 서울특별시)
}

