/// 이름·별칭 부분일치로 지역을 검색한다(대소문자·공백 무시).
List<Region> searchRegions(String query) {
  final q = query.trim().toLowerCase().replaceAll(' ', '');
  if (q.isEmpty) return koreaRegions;
  bool hit(String s) => s.toLowerCase().replaceAll(' ', '').contains(q);
  final exact = <Region>[];
  final partial = <Region>[];
  for (final r in koreaRegions) {
    if (r.name.toLowerCase() == q) {
      exact.add(r);
    } else if (hit(r.name) || r.aliases.any(hit)) {
      partial.add(r);
    }
  }
  return [...exact, ...partial];
}

/// 정확한 이름으로 지역을 찾는다. 없으면 null.
Region? regionByName(String name) {
  for (final r in koreaRegions) {
    if (r.name == name) return r;
  }
  return null;
}

/// 경도만 저장돼 있던 옛 데이터 호환 — 경도가 가장 가까운 지역.
Region nearestByLongitude(double lng) {
  var best = koreaRegions.first;
  var bestDiff = (best.lng - lng).abs();
  for (final r in koreaRegions) {
    final d = (r.lng - lng).abs();
    if (d < bestDiff) {
      best = r;
      bestDiff = d;
    }
  }
  return best;
}

/// 저장된 이름(우선)·경도로 지역을 되살린다. 이름이 맞으면 그대로, 아니면 경도 최근접.
Region resolveRegion(String? name, double lng) =>
    regionByName(name ?? '') ?? nearestByLongitude(lng);
