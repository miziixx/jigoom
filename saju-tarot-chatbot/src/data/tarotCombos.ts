/** 실존 조합 KB (정렬·중복 제거된 형태) */
const COMBO_LIST: TarotComboEntry[] = RAW.map((r) => ({
  cards: (r.a < r.b ? [r.a, r.b] : [r.b, r.a]) as [number, number],
  label: r.label,
  signal: r.signal,
}));

/** 조합 조회 맵: "id+id"(오름차순) → 엔트리 */
export const TAROT_COMBOS: Record<string, TarotComboEntry> = Object.fromEntries(
  COMBO_LIST.map((e) => [comboPairKey(e.cards[0], e.cards[1]), e]),
);

/** 전체 엔트리 (완결성 audit·검수 덤프용) */
export const TAROT_COMBO_LIST: TarotComboEntry[] = COMBO_LIST;

/** 감지된 조합 (어느 자리 카드끼리인지 포함) */
export interface DetectedCombo {
  entry: TarotComboEntry;
  a: DrawnTarotCard;
  b: DrawnTarotCard;
}

/**
 * 뽑힌 카드들 안에서 KB에 존재하는 카드 쌍을 모두 찾는다 (정·역방향 무관, 카드 정체성 기준).
 * 자리 순서(작은 position 먼저)로 정렬해 결정론적으로 반환한다.
 */
export function detectCardCombos(cards: DrawnTarotCard[]): DetectedCombo[] {
  const found: DetectedCombo[] = [];
  for (let i = 0; i < cards.length; i += 1) {
    for (let j = i + 1; j < cards.length; j += 1) {
      const entry = TAROT_COMBOS[comboPairKey(cards[i].card.id, cards[j].card.id)];
      if (entry) found.push({ entry, a: cards[i], b: cards[j] });
    }
  }
  return found;
}
