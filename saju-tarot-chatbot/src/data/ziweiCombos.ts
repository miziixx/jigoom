/** 주성 목록으로 조합 gloss를 찾는다. 실존 조합이 아니면 null. */
export function lookupZiweiCombo(starNames: string[]): ZiweiComboEntry | null {
  return COMBO_MAP.get(comboKey(starNames)) ?? null;
}

