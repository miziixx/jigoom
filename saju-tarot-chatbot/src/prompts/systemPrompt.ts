/**
 * 사건화 엔진 결과를 프롬프트 근거 블록으로 직렬화한다.
 * 활성(움직임 신호가 있는) 분야를 먼저 보여주고, 각 분야의 사건 패턴/타이밍/조심 신호/근거를 정리한다.
 * 표면 문구는 이미 쉬운 말이며, evidence만 전문가 근거용으로 유지한다.
 */
function formatEventForecast(chart: SajuChart, luck?: LuckCycles, gender?: Gender): string | null {
  const forecast = buildEventForecast(chart, luck, gender);
  if (!forecast) return null;

  const lines: string[] = [forecast.headline];
  // 활성 분야 먼저, 그다음 나머지
  const ordered = [
    ...forecast.activeDomains.map((k) => forecast.domains.find((d) => d.domain === k)!),
    ...forecast.domains.filter((d) => !forecast.activeDomains.includes(d.domain)),
  ];
  for (const d of ordered) {
    const tier = d.activation === "high" ? "지금 크게 움직임" : d.activation === "mid" ? "변화 신호 있음" : "평이함";
    const bits = [`■ ${d.label} [${tier}] — ${d.activationNote}`];
    if (d.patterns.length > 0) bits.push(`  · 나타나기 쉬운 일: ${d.patterns.join(" / ")}`);
    if (d.timingSignals.length > 0) bits.push(`  · 지금 시기 신호: ${d.timingSignals.join(" / ")}`);
    if (d.cautions.length > 0) bits.push(`  · 조심 신호: ${d.cautions.join(" / ")}`);
    if (d.evidence.length > 0) bits.push(`  · (근거) ${d.evidence.join("; ")}`);
    lines.push(bits.join("\n"));
  }
  return lines.join("\n");
}

function formatTarotCards(cards: DrawnTarotCard[]): string {
  return cards
    .map((c) => {
      const orientation = c.reversed ? "역방향" : "정방향";
      const meaning = c.reversed ? c.card.reversedMeaning : c.card.uprightMeaning;
      const label = c.positionLabel ? ` [${c.positionLabel}]` : "";
      const symbolism = describeTarotSymbolism(c.card);
      return [
        `${c.position}번째 자리${label}: ${c.card.name} (${orientation}, ${c.card.arcana === "major" ? "메이저" : "마이너"}) — ${meaning}`,
        `  상징 원형: ${symbolism.archetype}`,
        `  상징 키워드: ${symbolism.symbols.join(" · ")}`,
        `  그림 단서: ${symbolism.imagery}`,
        `  숫자/단계 의미: ${symbolism.numberTone}`,
        `  슈트 의미: ${symbolism.suitTone}`,
        `  관계 적용: ${symbolism.relationshipTone}`,
      ].join("\n");
    })
    .join("\n");
}

function formatTarotDiagnostics(cards: DrawnTarotCard[]): string {
  const upright = cards.filter((c) => !c.reversed).length;
  const reversed = cards.length - upright;
  const major = cards.filter((c) => c.card.arcana === "major").length;
  const suitCounts = cards.reduce<Record<string, number>>((acc, c) => {
    const suit = c.card.arcana === "major" ? "메이저" : tarotSuitOf(c.card);
    acc[suit] = (acc[suit] ?? 0) + 1;
    return acc;
  }, {});
  const repeatedSuits = Object.entries(suitCounts)
    .filter(([, count]) => count >= 2)
    .map(([suit, count]) => `${suit} ${count}장`);
  const first = cards[0];
  const last = cards[cards.length - 1];
  return [
    `정/역 비율: 정방향 ${upright}장 / 역방향 ${reversed}장`,
    `메이저 비율: ${major}장 / 전체 ${cards.length}장`,
    `반복 슈트: ${repeatedSuits.join(", ") || "뚜렷한 반복 없음"}`,
    first && last
      ? `흐름 축: 시작/핵심 ${first.card.name}(${first.reversed ? "역" : "정"}) → 마지막/조언 ${last.card.name}(${last.reversed ? "역" : "정"})`
      : "",
  ]
    .filter(Boolean)
    .join("\n");
}

function formatLuckCycles(luck: LuckCycles): string {
  const daYunLines = luck.daYun
    .map((dy) => `${dy.startAge}세~${dy.endAge}세 ${dy.ganZhi} (${dy.startYear}~${dy.endYear})${dy.current ? " ← 현재" : ""}`)
    .join(" / ");
  const lines = [
    `대운 흐름: ${daYunLines}`,
    `현재 대운: ${luck.currentDaYun ?? "대운 시작 전"}`,
    `세운(올해 ${luck.year}년, 입춘 기준): ${luck.yearGanZhi}`,
    `월운(이번 달 ${luck.month}월, 절기 기준): ${luck.monthGanZhi}`,
  ];
  if (luck.dayGanZhi) lines.push(`오늘 일진: ${luck.dayGanZhi}`);
  if (luck.luckInteractions) {
    lines.push(
      luck.luckInteractions.length > 0
        ? `운과 원국의 상호작용 (계산됨): ${luck.luckInteractions.join(", ")}`
        : "운과 원국의 상호작용 (계산됨): 현재 대운/세운/월운/일진과 원국 사이 새로 성립하는 합충형파해 없음",
    );
  }
  if (luck.yearlyFlow && luck.yearlyFlow.length > 0) {
    const yearLines = luck.yearlyFlow.map(
      (yf) =>
        `${yf.year}년(${yf.age}세) ${yf.ganZhi}${yf.current ? " ← 올해" : ""}${yf.interactions.length > 0 ? ` — ${yf.interactions.join(", ")}` : " — 원국과 새 상호작용 없음"}`,
    );
    lines.push(`앞으로 10년 세운 흐름 (입춘 기준, 계산됨):\n${yearLines.join("\n")}`);
  }
  if (luck.monthlyFlow && luck.monthlyFlow.length > 0) {
    const monthLines = luck.monthlyFlow.map(
      (mf) =>
        `${mf.month}월 ${mf.ganZhi}${mf.interactions.length > 0 ? ` — ${mf.interactions.join(", ")}` : " — 원국과 새 상호작용 없음"}`,
    );
    lines.push(`올해 ${luck.year}년 월별 월운 흐름 (절기 기준, 계산됨):\n${monthLines.join("\n")}`);
  }
  return lines.join("\n");
}

