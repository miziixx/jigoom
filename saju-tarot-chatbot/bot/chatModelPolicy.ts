// 잡담 vs 사주 해석을 나눠 값싼 모델로 태울지 결정하는 순수 정책.
// (teacher.ts는 로드 시 Anthropic 클라이언트/API 키를 요구하므로, 테스트 가능하도록
//  모델 선택의 판단부만 여기 분리한다.)

// 사주/타로/명리 용어. generalChat(미분류 폴백 포함)에 이 용어가 섞이면 정확도를 위해
// 값싼 모델로 낮추지 않는다.
// 주의: 합/충/형/파/해 같은 '단일 글자'는 합정·충전·이해·파일·해요 등 일상어를 사주로
// 오인해 잡담을 불필요하게 비싼 모델로 보내므로 넣지 않는다. 실제 사주 질문은 거의 항상
// 다른 명리 용어(일간·지지·오행 등)가 함께 들어오므로 그것으로 잡힌다.
export const SAJU_HINT =
  /사주|팔자|명리|일간|일지|월지|년지|연지|시지|지장간|투출|통근|용신|기신|십성|비겁|겁재|비견|식상|식신|상관|재성|편재|정재|관성|편관|정관|칠살|인성|편인|정인|대운|세운|월운|일진|신강|신약|중화|격국|신살|오행|천간|지지|도화살|역마|화개|괴강|양인|백호|공망|삼재|형충|충형|삼합|육합|반합|궁합|타로|점성|운세|사주팔자/;

/**
 * 이 질문을 값싼 잡담용 모델로 태울지 여부.
 * - generalChat(순수 잡담·미분류 폴백)이고
 * - 사주/타로 용어가 없을 때만 true.
 */
export function shouldUseChatModel(intent: string, question: string): boolean {
  return intent === "generalChat" && !SAJU_HINT.test(question);
}
