// 메시지가 "사주 등록 시도"인지 "이론 질문/대화"인지 가르는 순수 휴리스틱(부작용 없음 → 단위 테스트 가능).

// 명리 이론 용어(십성·오행 판정 등). 이게 섞인 메시지는 대개 "사주 등록 시도"가 아니라 "이론 질문"이라,
// 부분 팔자 안내로 가로채지 말고 선생님(askTeacher)이 답하게 한다.
const THEORY_TERMS =
  /십성|편재|정재|편관|정관|식신|상관|비견|겁재|편인|정인|인성|식상|재성|관성|비겁|용신|기신|신강|신약|격국|지장간|십이운성|공망/;

/** 부분 간지처럼 보여도 사실은 이론 질문/대화인지 (물음표나 이론 용어가 있으면). */
export function carriesRealQuestion(text: string): boolean {
  return /[?？]/.test(text) || THEORY_TERMS.test(text);
}
